test("weekly agent news reports tender wins from live state rather than inventing stories",()=>{
 const s=setup();const edition1=endWeek(s,fx)!;
 acknowledgeEdition(s,edition1.id);
 const edition2=endWeek(s,fx)!;
 assert.equal(edition2.weekCompleted,2);
 const dated=s.ceo!.rivalNews?.filter(e=>e.day>=edition2.dayFrom&&e.day<=edition2.dayTo)||[];
 assert.ok(edition2.articles.filter(a=>a.category==="competition").every(a=>dated.some(e=>a.headline===e.message)));
 assert.equal(edition2.rivalsWon,s.ceo!.rivals.reduce((n,r)=>n+(r.wins??0),0)-s.ceo!.rivals.reduce((n,r)=>n+(r.wins??0),0)+edition2.rivalsWon);
});
test("old saves with no newspaper state migrate to the manual week containing their saved day",()=>{
 const s=setup();s.ceo!.day=29;delete (s as any).clock;delete s.ceo!.weekly;s.ceo!.speed=3;s.ceo!.pauseOnIssue=true;
 const m=migrate(JSON.parse(JSON.stringify(s)));
 assert.equal(m.ceo!.day,29);
 assert.equal(m.ceo!.weekly?.week,5);
 assert.equal(m.ceo!.speed,0);
 assert.equal(m.ceo!.pauseOnIssue,false);
 assert.equal(m.ceo!.weekly?.editions.length,0);
 const edition=endWeek(m,fx);
 assert.equal(edition?.dayFrom,30);
 assert.equal(m.ceo!.day,36);
});
