import test from "node:test";
import assert from "node:assert/strict";
import {defaults,migrate,newCEO} from "../src/game/state";
import {captureDecision,endWeek,acknowledgeEdition,unreadEdition,weeklyOf} from "../src/game/weekly";
import {hire,qualify,startPitch,presentPitch,counter} from "../src/game/ceo";
import type {Fx} from "../src/game/store";
const fx:Fx={toast:()=>{},log:()=>{}};
const setup=()=>{const s=defaults();s.created=true;s.agencyUnlocked=true;s.cityUnlocked=true;s.ceo=newCEO(51);s.ceo.weekly=s.clock;s.agencyCash=180000000;s.reputation=51;return s};
test("CEO days are manual: hiring, qualifying and pitch preparation do not advance the week",()=>{
 const s=setup();const day=s.ceo!.day;
 hire(s,fx,"researcher");qualify(s,fx,"sora");startPitch(s,fx,"sora");presentPitch(s);
 assert.equal(s.ceo!.day,day);
 assert.equal(weeklyOf(s).week,1);
});
test("End Week runs exactly seven days regardless of legacy speed and publishes observable financial and market events",()=>{
 const s=setup();const c=s.ceo!;
 c.speed=0;
 const balance=s.agencyCash;
 const edition=endWeek(s,fx);
 assert.ok(edition);
 assert.equal(c.day,8);
 assert.equal(c.weekly!.week,2);
 assert.equal(edition!.weekCompleted,1);
 assert.equal(edition!.weekStarted,2);
 assert.equal(edition!.dayFrom,2);
 assert.equal(edition!.dayTo,8);
 assert.equal(edition!.cashBefore,balance);
 assert.equal(edition!.cashAfter,s.agencyCash);
 assert.equal(edition!.read,false);
 assert.ok(edition!.articles.some(x=>x.category==="finance"));
 assert.ok(edition!.articles.every(x=>x.evidence.length>2));
 assert.ok(edition!.articles.some(x=>x.category==="decisions"));
 assert.ok(unreadEdition(s));
});
test("unread newspaper prevents accidentally skipping another week; after reading, manual button advances one further turn",()=>{
 const s=setup();
 endWeek(s,fx);
 const stored=JSON.parse(JSON.stringify(s));
 assert.equal(endWeek(s,fx),null);
 assert.equal(s.ceo!.day,8);
 const restored=migrate(stored);
 assert.equal(unreadEdition(restored)?.weekCompleted,1);
 acknowledgeEdition(restored,unreadEdition(restored)!.id);
 assert.equal(unreadEdition(restored),null);
 const next=endWeek(restored,fx);
 assert.equal(next?.weekCompleted,2);
 assert.equal(restored.ceo!.day,15);
 assert.equal(restored.ceo!.weekly?.editions.length,2);
});
